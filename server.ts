// Helper to format detailed PayPhone error messages into readable strings
function formatPayPhoneError(data: any): string {
  if (!data) return 'Error desconocido de pasarela';
  if (typeof data === 'string') return data;

  let msg = data.message || data.error || data.payphoneMessage || '';
  if (data.errors) {
    if (typeof data.errors === 'string') {
      msg += (msg ? ': ' : '') + data.errors;
    } else if (Array.isArray(data.errors)) {
      msg += (msg ? ': ' : '') + data.errors.map((e: any) => (typeof e === 'object' ? JSON.stringify(e) : String(e))).join(', ');
    } else if (typeof data.errors === 'object') {
      const details = Object.entries(data.errors)
        .map(([k, v]) => `${k}: ${Array.isArray(v) ? v.join(', ') : (typeof v === 'object' ? JSON.stringify(v) : String(v))}`)
        .join('; ');
      msg += (msg ? ': ' : '') + details;
    }
  }
  return msg || JSON.stringify(data, null, 2);
}

// In-Memory Idempotency Cache to prevent duplicate transaction confirmations
interface ConfirmedTransactionRecord {
  clientTxId: string;
  transactionId: number | string;
  amount: number;
  authorizationCode?: string;
  cardBrand?: string;
  lastDigits?: string;
  confirmedAt: string;
  status: string;
}

