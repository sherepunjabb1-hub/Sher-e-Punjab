// 2. /api/create-payment (PayPhone Button Prepare Endpoint)
// Accepts amount and clientTxId. Calls https://pay.payphonetodoesposible.com/api/button/Prepare
// Returns payWithPayPhone URL generated by PayPhone.
// ============================================================================
app.post(['/api/create-payment', '/api/payphone/create'], async (req, res) => {
  try {
    const {
      amount: rawAmount,
      totalAmount,
      totalDollars,
      clientTxId: rawClientTxId,
      clientTransactionId,
      reference,
      customerEmail,
      customerPhone,
      email,
      phoneNumber,
    } = req.body || {};

    const total = Number(rawAmount ?? totalAmount ?? totalDollars ?? 0);
    if (!total || total <= 0) {
      return res.status(400).json({
        success: false,
        error: 'Amount must be a positive number greater than 0',
      });
    }

    // 1. Amount Breakdown Formula: Pure integer in cents (e.g. 11.85 -> 1185)
    // PayPhone strictly requires: amount = amountWithoutTax + amountWithTax + tax + service + tip
    const totalCents = Math.round(total * 100);
    const amountWithoutTax = totalCents;
    const amountWithTax = 0;
    const tax = 0;
    const service = 0;
    const tip = 0;

    // 2. Data Types & Formats
    // Clean alphanumeric string (max 50 characters, NO spaces, NO special characters except hyphens)
    const rawTxId = clientTransactionId || rawClientTxId || `SHERE-${Date.now()}`;
    const cleanClientTxId = String(rawTxId)
      .replace(/[^a-zA-Z0-9-]/g, '')
      .slice(0, 50);

    // Reference: plain string without unsupported characters (max 30 characters)
    const cleanReference = String(reference || `Order ${cleanClientTxId}`)
      .replace(/[^a-zA-Z0-9 -]/g, '')
      .trim()
      .slice(0, 30);

    // Clean secret token and store ID from environment variables
    const rawToken = process.env.PAYPHONE_SECRET_TOKEN || process.env.PAYPHONE_BEARER_TOKEN || PAYPHONE_SECRET_TOKEN;
    const cleanToken = rawToken ? rawToken.replace(/^Bearer\s+/i, '').replace(/["'\r\n]/g, '').trim() : '';
    const rawStoreId = process.env.PAYPHONE_STORE_ID || PAYPHONE_STORE_ID || '138280';
    const cleanStoreId = String(rawStoreId).replace(/["'\r\n]/g, '').trim();

    // Clean phone number (numeric digits only)
    const rawPhone = phoneNumber || customerPhone || '';
    const cleanPhone = rawPhone ? String(rawPhone).replace(/\D/g, '') : '';

    const rawEmail = email || customerEmail || '';
    const cleanEmail = rawEmail ? String(rawEmail).trim() : '';

    const payload: any = {
      amount: totalCents,
      amountWithoutTax: amountWithoutTax,
      amountWithTax: amountWithTax,
      tax: tax,
      service: service,
      tip: tip,
      currency: 'USD',
      clientTransactionId: cleanClientTxId,
      storeId: cleanStoreId,
      reference: cleanReference || 'Sher-e-Punjab Order',
      responseUrl: PAYPHONE_RESPONSE_URL,
      cancellationUrl: PAYPHONE_RESPONSE_URL,
    };

    if (cleanEmail) {
      payload.email = cleanEmail;
    }
    if (cleanPhone) {
      payload.phoneNumber = cleanPhone;
    }

    console.log(`[PayPhone API] Calling Prepare API for clientTxId ${cleanClientTxId}:`, JSON.stringify(payload, null, 2));

    const payphoneHeaders = {
      'Authorization': `Bearer ${cleanToken}`,
      'Content-Type': 'application/json',
      'Accept': 'application/json, text/plain, */*',
      'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
    };

    const response = await fetch(`${PAYPHONE_API_BASE}/Prepare`, {
      method: 'POST',
      headers: payphoneHeaders,
      body: JSON.stringify(payload),
    });

    const responseText = await response.text();
    console.log(`[PayPhone API] Raw Prepare Status: ${response.status}`);

    let data: any = null;
    try {
      data = JSON.parse(responseText);
    } catch {
      data = { rawText: responseText };
    }

    console.log('[PayPhone API Prepare Response]:', JSON.stringify(data, null, 2));

    if (!response.ok) {
      console.error('PayPhone Error Detail:', JSON.stringify(data, null, 2));
      const formattedError = formatPayPhoneError(data);

      return res.status(response.status || 400).json({
        success: false,
        error: formattedError,
        message: formattedError,
        payphoneMessage: formattedError,
        details: data,
        sentPayload: payload,
      });
    }

    const token =
      data?.token ||
      (typeof data === 'string' && data.length > 20 ? data : null) ||
      data?.payUrl ||
      data?.paymentUrl;

    const paymentId = data?.paymentId || data?.id || data?.transactionId || null;

    // Generate payWithPayPhone URL from PayPhone response or token
    const payWithPayPhone =
      data?.payWithPayPhone ||
      (token ? `https://pay.payphonetodoesposible.com/pay?token=${encodeURIComponent(token)}` : null);

    if (!payWithPayPhone) {
      console.error('PayPhone Error Detail (No pay URL returned):', JSON.stringify(data, null, 2));
      const errMsg = formatPayPhoneError(data) || 'No payment URL or token received from PayPhone';
      return res.status(400).json({
        success: false,
        error: errMsg,
        message: errMsg,
        payphoneMessage: errMsg,
        details: data,
      });
    }

    console.log(`[PayPhone API] Generated payWithPayPhone URL for ${cleanClientTxId}:`, payWithPayPhone);

    return res.json({
      success: true,
      paymentUrl: payWithPayPhone,
      payWithPayPhone: payWithPayPhone,
      token: token,
      paymentId: paymentId,
      clientTxId: cleanClientTxId,
      clientTransactionId: cleanClientTxId,
      storeId: cleanStoreId,
      appId: PAYPHONE_APP_ID,
      amount: total,
      amountInCents: totalCents,
    });
  } catch (error: any) {
    console.error('PayPhone Error Detail (Exception):', error);
    const errString = error?.message ? String(error.message) : JSON.stringify(error, null, 2);
    return res.status(500).json({
      success: false,
      error: errString,
      message: errString,
      payphoneMessage: errString,
    });
  }
});

